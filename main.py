# メインスレッドでキャッチされない例外をログに残すフック
def _log_unhandled_exception(exc_type, exc_value, exc_tb):
    # KeyboardInterrupt は標準の挙動に任せる
    if exc_type is KeyboardInterrupt:
        sys.__excepthook__(exc_type, exc_value, exc_tb)
        return
    logging.critical('未捕捉例外', exc_info=(exc_type, exc_value, exc_tb))

sys.excepthook = _log_unhandled_exception


# スレッド内での未捕捉例外をログに残す（Python 3.8+ の場合）
def _thread_excepthook(args):
    try:
        # args は exc_type, exc_value, exc_traceback, thread を含む
        logging.critical('スレッド内で未捕捉例外: %s', getattr(args, 'thread', None), exc_info=(args.exc_type, args.exc_value, args.exc_traceback))
    except Exception:
        logging.exception('threading.excepthook 処理中にエラー')

try:
    threading.excepthook = _thread_excepthook
except Exception:
    # 古い Python では threading.excepthook が存在しないため無視
    pass


# プロセス終了シグナルを受け取ったらログを残して終了する
def _handle_signal(signum, frame):
    global _MANUAL_STOP_REQUESTED
    _MANUAL_STOP_REQUESTED = True
    logging.info('シグナル %s 受信、終了します', signum)
    # ハンドラをフラッシュ
    for h in list(logging.getLogger().handlers):
        try:
            h.flush()
        except Exception:
            pass
    sys.exit(0)

try:
    signal.signal(signal.SIGTERM, _handle_signal)
    signal.signal(signal.SIGINT, _handle_signal)
except Exception:
    # Windows や制限環境では例外が出る場合があるが安全に無視
    pass


def read_free_intervals_for_today(user_id: Optional[str] = None) -> List[Tuple[datetime, datetime]]:
    """当日の freebusy CSV を読み、(開始, 終了) のタイムゾーン付き datetime リストを返す。
    ファイルが無ければ空リストを返す。
    """
    today_tag = datetime.now().strftime('%Y-%m-%d')
    # per-user freebusy CSV: data_output/<sanitized_user>/date/freebusy_YYYY-MM-DD.csv
    if user_id:
        try:
            safe = storage_sqlite._sanitize_user_id(user_id)
            path = os.path.join('data_output', safe, 'date', f'freebusy_{today_tag}.csv')
        except Exception:
            path = os.path.join(FREEBUSY_CSV_DIR, f'freebusy_{today_tag}.csv')
    else:
        path = os.path.join(FREEBUSY_CSV_DIR, f'freebusy_{today_tag}.csv')
    if not os.path.exists(path):
        return []
    intervals = []
    with open(path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for r in reader:
            try:
                # prefer start_local / end_local if present with tz
                s = r.get('start_local') or r.get('start_iso')
                e = r.get('end_local') or r.get('end_iso')
                # try parse with timezone
                try:
                    start_dt = datetime.strptime(s, '%Y-%m-%d %H:%M %z')
                except Exception:
                    try:
                        start_dt = datetime.fromisoformat(s)
                    except Exception:
                        start_dt = datetime.strptime(s, '%Y-%m-%d %H:%M')
                        start_dt = start_dt.replace(tzinfo=datetime.now().astimezone().tzinfo)
                try:
                    end_dt = datetime.strptime(e, '%Y-%m-%d %H:%M %z')
                except Exception:
                    try:
                        end_dt = datetime.fromisoformat(e)
                    except Exception:
                        end_dt = datetime.strptime(e, '%Y-%m-%d %H:%M')
                        end_dt = end_dt.replace(tzinfo=datetime.now().astimezone().tzinfo)
                intervals.append((start_dt, end_dt))
            except Exception:
                continue
    return intervals



def detect_events(parsed: List[Tuple[datetime, Any, Any]], now: datetime, curr_interval: Tuple[datetime, datetime],
                  threshold_steps: int = 20) -> List[Dict[str, Any]]:
    """Detect increase and no-movement events from parsed samples."""
    events = []
    try:
        if not parsed:
            return events
        parsed_sorted = sorted(parsed, key=lambda x: x[0])

        # detect increase anchored at last HR-present
        last_hr_idx = None
        for i in range(len(parsed_sorted) - 1, -1, -1):
            if parsed_sorted[i][1] is not None:
                last_hr_idx = i
                break
        if last_hr_idx is not None:
            last_hr_ts = parsed_sorted[last_hr_idx][0]
            window_start = last_hr_ts - timedelta(minutes=5)
            window = [p for p in parsed_sorted if window_start <= p[0] <= last_hr_ts]
            window.sort(key=lambda x: x[0])
            for j in range(1, len(window)):
                prev = window[j - 1]
                curr = window[j]
                prev_steps = prev[2]
                curr_steps = curr[2]
                if isinstance(prev_steps, (int, float)) and isinstance(curr_steps, (int, float)):
                    if curr_steps - prev_steps >= threshold_steps:
                        events.append({
                            'type': 'increase',
                            'ts': curr[0],
                            'prev_steps': prev_steps,
                            'curr_steps': curr_steps,
                            'diff': curr_steps - prev_steps,
                        })
                        break

        # detect no-movement: contiguous 10-sample block ending at last HR-present
        if len(parsed_sorted) >= 10:
            last_hr_idx = None
            for i in range(len(parsed_sorted) - 1, -1, -1):
                if parsed_sorted[i][1] is not None:
                    last_hr_idx = i
                    break
            if last_hr_idx is not None and last_hr_idx >= 9:
                block_start = last_hr_idx - 9
                block = parsed_sorted[block_start:last_hr_idx + 1]
                all_zero = True
                for ts, hr, steps in block:
                    if not (curr_interval[0] <= ts <= curr_interval[1]):
                        all_zero = False
                        break
                    if not isinstance(steps, (int, float)) or steps != 0:
                        all_zero = False
                        break
                if all_zero:
                    events.append({'type': 'no_movement', 'ts': parsed_sorted[last_hr_idx][0]})
    except Exception:
        logging.exception('detect_events failed')
    return events


def evaluate_parsed_and_enqueue(user_id: str, parsed: list, now: datetime, curr_interval: Tuple[datetime, datetime], slack_cfg):
    """Detect events and launch the checkbox survey session for each eligible event."""
    try:
        try:
            if fitbit_sleep.is_in_median_sleep_window(user_id, now, max_items=14):
                logging.info('Median sleep window suppression: user=%s', user_id)
                return
        except Exception:
            logging.exception('Median sleep window check failed for user=%s; continuing notifications', user_id)

        events = detect_events(parsed, now, curr_interval)
        channel = slack_cfg[1] if slack_cfg else None
        for ev in events:
            # Determine detection_type based on event
            if ev.get('type') == 'no_movement':
                detection_type = 'no_movement'
                recommended_types = ['stretch', 'strength']
            else:
                detection_type = 'motion'
                recommended_types = ['cardio', 'strength']

            # AI will choose the actual exercise type from recommended_types;
            # use recommended_types[0] only as a label/fallback before the AI responds.
            fallback_exercise_type = recommended_types[0]

            # Build AI context (may read DB but doesn't modify send state)
            try:
                ai_context = storage_sqlite.build_exercise_ai_input(
                    user_id=user_id,
                    exercise_type=fallback_exercise_type,
                    exercise_name=None,
                    event={
                        'type': ev.get('type'),
                        'ts': ev.get('ts'),
                    },
                    limit=5,
                )
            except Exception:
                logging.exception('Failed to build exercise AI input for user=%s', user_id)
                ai_context = {
                    'exercise_type': fallback_exercise_type,
                    'motion_detected': ev.get('type') != 'no_movement',
                    'detected_event_type': ev.get('type'),
                    'detected_at': ev.get('ts').isoformat() if ev.get('ts') and hasattr(ev.get('ts'), 'isoformat') else None,
                    'pre_survey': {'visibility': None},
                    'recent_exercises': [],
                    'adherence_by_type': [],
                }

            # Add detection_type and recommended_types to AI context
            ai_context['detection_type'] = detection_type
            ai_context['recommended_types'] = recommended_types

            # Critical section: serialize per-user actions and enforce cooldown
            # for both motion and no_movement paths to avoid duplicate launches.
            try:
                with storage_sqlite.user_lock(user_id):
                    # Re-check last sent time under lock to avoid races
                    last_sent = storage_sqlite.get_last_sent_time(user_id)
                    allow = True
                    if last_sent:
                        try:
                            diff = datetime.now().astimezone() - last_sent
                            if diff.total_seconds() < NOTIFY_COOLDOWN_SECONDS:
                                allow = False
                        except Exception:
                            allow = True
                    if not allow:
                        continue

                    # If this is a no_movement detection, launch the interactive pre-survey
                    # session which will handle pre-survey -> exercise message -> post-survey
                    # in a separate process.
                    if detection_type == 'no_movement':
                        try:
                            # channel may be None if slack_cfg missing; guard the call
                            try:
                                send_slack_checkbox.launch_session(
                                    user_id=user_id,
                                    channel=channel,
                                    motion_detected=False,
                                    exercise_type=fallback_exercise_type,
                                    ai_context=ai_context,
                                    detection_type=detection_type,
                                )
                            except TypeError:
                                # older launch_session signatures may not accept kwargs
                                send_slack_checkbox.launch_session(user_id, channel, False, fallback_exercise_type, ai_context, detection_type)
                        except Exception:
                            logging.exception('Failed to launch send_slack_checkbox session for no_movement')
                        # Skip the enqueue path since interactive flow will send message
                        continue

                    # motion detection path: AI picks exercise type from recommended_types.
                    message_text = send_slack_checkbox._fallback_exercise_message(
                        fallback_exercise_type,
                        detection_type,
                    )
                    try:
                        ai_payload = send_slack_checkbox._generate_exercise_payload(
                            user_id=user_id,
                            exercise_type=fallback_exercise_type,
                            pre_survey={},
                            ai_context=ai_context if isinstance(ai_context, dict) else None,
                            detection_type=detection_type,
                        )
                        # Use AI-chosen category if returned; otherwise fall back.
                        chosen_exercise_type = ai_payload.get('category') if isinstance(ai_payload, dict) else None
                        if chosen_exercise_type not in ('stretch', 'cardio', 'strength'):
                            chosen_exercise_type = fallback_exercise_type
                        chosen_exercise_name = ai_payload.get('exercise_name') if isinstance(ai_payload, dict) else None
                        if not isinstance(chosen_exercise_name, str) or not chosen_exercise_name.strip():
                            chosen_exercise_name = send_slack_checkbox._exercise_name(chosen_exercise_type)
                        message_text = ai_payload.get('message') if isinstance(ai_payload, dict) else None
                        if not isinstance(message_text, str) or not message_text.strip():
                            message_text = send_slack_checkbox._fallback_exercise_message(
                                chosen_exercise_type,
                                detection_type,
                            )

                        nid = storage_sqlite.create_sent_notification(
                            user_id=user_id,
                            exercise_name=chosen_exercise_name,
                            exercise_type=chosen_exercise_type,
                            message_text=message_text,
                            ai_category=ai_payload.get('category') if isinstance(ai_payload, dict) else None,
                            ai_rationale=ai_payload.get('rationale') if isinstance(ai_payload, dict) else None,
                            reps=ai_payload.get('reps') if isinstance(ai_payload, dict) else None,
                            sets=ai_payload.get('sets') if isinstance(ai_payload, dict) else None,
                            duration_min=ai_payload.get('duration_min') if isinstance(ai_payload, dict) else None,
                            detection_type=detection_type,
                            ai_context=ai_context if isinstance(ai_context, dict) else None,
                        )
                        storage_sqlite.create_pending_response(nid, user_id)
                    except Exception:
                        logging.exception('Failed to create sent notification record')
                        chosen_exercise_type = fallback_exercise_type
                        nid = None

                    # Enqueue message with post-survey blocks so users can answer implementation/adherence.
                    # For motion detection, include the generated exercise message inside blocks
                    # (first section) so Slack shows message -> questionnaire in that order.
                    try:
                        motion_blocks = []
                        if message_text:
                            motion_blocks.append({
                                'type': 'section',
                                'text': {'type': 'mrkdwn', 'text': message_text},
                            })
                        motion_blocks.extend(send_slack_checkbox.build_post_survey_blocks(chosen_exercise_type))
                        payload = json.dumps(motion_blocks, ensure_ascii=False)
                        storage_sqlite.enqueue_notification_for_user(
                            user_id,
                            message_text or '運動を実施しましたか？',
                            notification_id=nid,
                            payload=payload,
                        )
                    except Exception:
                        logging.exception('Failed to enqueue notification for user=%s', user_id)
            except Exception:
                logging.exception('Failed during locked enqueue for user=%s', user_id)
    except Exception:
        logging.exception('evaluate_parsed_and_enqueue (wrapper) failed')


