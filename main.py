def calendar_updater(stop_event: threading.Event, users: List[str]):
    """スレッド: CALENDAR_INTERVAL 秒ごとにカレンダーの free/busy CSV を更新する（ユーザごとに google_calendar_freebusy.main を呼ぶ）。"""
    logging.info('Calendar updater started (interval=%s sec)', CALENDAR_INTERVAL)
    while not stop_event.is_set():
        for user in users:
            try:
                logging.info('Calendar update starting for %s', user)
                google_calendar_freebusy.main(account_id=user)
                logging.info('Calendar update succeeded for %s', user)
            except Exception:
                logging.exception('Calendar update failed for user=%s', user)
        # wait
        stop_event.wait(CALENDAR_INTERVAL)


def get_users_from_db() -> List[str]:
    """Return a list of user IDs to process. Prefer `fitbit_tokens.user_id`, fall back to google_calendar_tokens.account_id."""
    # No local SQLite fallback: rely on central Postgres via db.connect()
    db = os.environ.get('TOKEN_DB') or os.environ.get('FITBIT_TOKEN_DB') or None
    users = []
    try:
        # use db.connect() which will connect to DATABASE_URL if set
        conn = db_connect()
        cur = conn.cursor()
        try:
            cur.execute('SELECT DISTINCT user_id FROM fitbit_tokens')
            rows = cur.fetchall()
            users = [r[0] for r in rows if r and r[0]]
        except Exception:
            users = []
        if not users:
            try:
                cur.execute('SELECT DISTINCT account_id FROM google_calendar_tokens')
                rows = cur.fetchall()
                users = [r[0] for r in rows if r and r[0]]
            except Exception:
                users = []
    except Exception:
        logging.exception('Failed to read users from DB')
        users = []
    finally:
        try:
            conn.close()
        except Exception:
            pass
    return users


def full_day_updater(stop_event: threading.Event, user_id: str):
    """スレッド: 定期的に1日の per-minute データを取得し、日次 JSON に保存（マージ）する。"""
    logging.info('Full-day updater started (interval=%s sec)', FULLDAY_INTERVAL)
    while not stop_event.is_set():
        try:
            today = datetime.now().strftime('%Y-%m-%d')
            logging.info('Full-day fetch for %s', today)
            per_minute, summary = fitbit_sampler.fetch_day(user_id, today, include_summary=True)
            saved = fitbit_sampler.save_day_json(
                user_id,
                today,
                per_minute,
                out_dir=VALUE_JSON_DIR,
                resting_heart_rate=(summary or {}).get('resting_heart_rate'),
            )
            logging.info('Saved day file: %s', saved)
            # optionally upsert into DB so full-day fetch fills missing values saved as NULL by realtime
            # Disabled by default to avoid unexpected writes; enable by setting env FULLDAY_UPSERT_ENABLED=1
            try:
                if os.environ.get('FULLDAY_UPSERT_ENABLED', '0') == '1':
                    try:
                        storage_sqlite.upsert_samples_from_per_minute(user_id, today, per_minute)
                    except Exception:
                        logging.exception('Failed to upsert full-day samples into DB')
            except Exception:
                logging.exception('Full-day DB upsert encountered error')
        except Exception:
            logging.exception('Full-day update failed')
        stop_event.wait(FULLDAY_INTERVAL)


def _notifier_loop(stop_event: threading.Event, interval: int = 5):
    """通知キューを定期的にポーリングして notifier_worker に処理を委譲するデーモンスレッド用ループ。"""
    try:
        import notifier_worker
    except Exception:
        logging.exception('Notifier module not available; notifier loop exiting')
        return
    logging.info('Notifier loop started (interval=%s sec)', interval)
    while not stop_event.is_set():
        try:
            notifier_worker.process_batch(limit=10, do_send=True)
        except Exception:
            logging.exception('Notifier loop error')
        stop_event.wait(interval)


def sampler_loop(sampler: Sampler, stop_event: threading.Event, slack_cfg):
    logging.info('Sampler loop started (interval=%s sec)', SAMPLE_INTERVAL)
    while not stop_event.is_set():
        now = datetime.now().astimezone()
        try:
            fitbit_sleep.refresh_recent_sleep_history_if_due(sampler.user_id, now)

            # Evaluate events only during free intervals. Per-minute samples are
            # collected by full_day_updater and written to the same day JSON file.
            intervals = read_free_intervals_for_today(sampler.user_id)
            in_free = False
            curr_interval = None
            for s, e in intervals:
                if s <= now <= e:
                    in_free = True
                    curr_interval = (s, e)
                    break
            if in_free and curr_interval:
                # Use recent samples (day JSON file) within last 60 minutes for decisions
                try:
                    recent_rows = storage_sqlite.get_recent_samples(sampler.user_id, minutes=60)
                except Exception:
                    logging.exception('Failed to get recent samples')
                    recent_rows = []

                # normalize recent_rows to list of (ts(datetime), heart_rate, steps)
                parsed = []
                for r in recent_rows:
                    try:
                        ts = datetime.fromisoformat(r[0])
                        parsed.append((ts, r[1], r[2]))
                    except Exception:
                        continue

                # evaluate parsed samples using shared logic
                evaluate_parsed_and_enqueue(sampler.user_id, parsed, now, curr_interval, slack_cfg)
        except Exception:
            logging.exception('Evaluation failed')
        # wait until next sample
        stop_event.wait(SAMPLE_INTERVAL)


def main():
    global _RESTART_REQUESTED, _RESTART_REASON, _MANUAL_STOP_REQUESTED
    # Reset process-level control flags for each fresh main() run.
    _RESTART_REQUESTED = False
    _RESTART_REASON = None
    _MANUAL_STOP_REQUESTED = False
    # load slack config
    # channel mapping is stored in tokens.db; bot token is read from slack_test.py
    token = None
    # load slack token from slack_notifier (env or module constants)
    token_cfg = slack_notifier.get_slack_config()
    if token_cfg:
        token = token_cfg[0]

    # determine users to process from DB (fitbit_tokens preferred)
    users = get_users_from_db()
    if not users:
        users = [USER_ID]
    logging.info('Users to process: %s', users)

    # per-user samplers
    samplers = {u: Sampler(u) for u in users}

    # Ensure DB schema / PRAGMA for better concurrency
    try:
        storage_sqlite.ensure_schema()
    except Exception:
        logging.exception('Failed to ensure DB schema')
    
    # normal continuous mode
    stop_event = threading.Event()

    # start calendar updater (single)
    cal_thread = threading.Thread(target=calendar_updater, args=(stop_event, users), daemon=True)
    cal_thread.start()

    # start per-user full-day and sampler threads
    user_threads = []
    for user, sampler in samplers.items():
        # per-user slack cfg
        channel = tokens_db.get_channel_for_user(user)
        if not channel:
            logging.warning('Slack channel not found in tokens.db for user=%s; notifications may be disabled for this user', user)
        if not token:
            logging.warning('Slack bot token not found in slack_notifier; notifications will be disabled')
        slack_cfg_user = (token, channel) if token and channel else None

        t_full = threading.Thread(target=full_day_updater, args=(stop_event, user), daemon=True)
        t_full.start()
        user_threads.append(t_full)

        t_samp = threading.Thread(target=sampler_loop, args=(sampler, stop_event, slack_cfg_user), daemon=True)
        t_samp.start()
        user_threads.append(t_samp)

    # start notifier loop only when central socket_server is not running.
    # Keeping a single sender process avoids duplicate Slack posts for one DB queue item.
    notifier_thread = None
    try:
        socket_server_running = lock_db.is_held('socket_server')
    except Exception:
        socket_server_running = False

    if socket_server_running:
        logging.info('socket_server DB lock detected; skip main notifier loop')
    else:
        notifier_thread = threading.Thread(target=_notifier_loop, args=(stop_event,), daemon=True)
        notifier_thread.start()

    logging.info('main: running. press Ctrl+C to stop')
    try:
        while True:
            if not cal_thread.is_alive():
                request_process_restart('calendar_updater thread stopped unexpectedly')
                break
            time.sleep(1)
    except KeyboardInterrupt:
        _MANUAL_STOP_REQUESTED = True
        logging.info('Stopping...')
    finally:
        if _MANUAL_STOP_REQUESTED:
            # Manual stop always wins over automatic self-restart.
            _RESTART_REQUESTED = False
            _RESTART_REASON = None
        stop_event.set()
        cal_thread.join(timeout=5)
        for t in user_threads:
            try:
                t.join(timeout=5)
            except Exception:
                pass
        if notifier_thread is not None:
            notifier_thread.join(timeout=5)

    return _RESTART_REQUESTED


if __name__ == '__main__':
    # Acquire single-instance DB lock to avoid multiple Socket Mode clients
    try:
        lock_owner = lock_db.make_owner()
        if not lock_db.acquire('main', lock_owner):
            logging.error('Another instance appears to be running (DB lock main is held). Exiting.')
            sys.exit(1)
        heartbeat_stop = lock_db.start_heartbeat('main', lock_owner)

        should_restart = False
        try:
            should_restart = main()
        finally:
            heartbeat_stop.set()
            lock_db.release('main', lock_owner)

        if should_restart:
            try:
                logging.critical('Restarting main process now. reason=%s', _RESTART_REASON)
            except Exception:
                pass
            os.execv(sys.executable, [sys.executable] + sys.argv)
    except SystemExit:
        raise
    except Exception:
        logging.exception('Failed to start main with instance lock')
