# Load .env into environment early so modules that read env see values.
def _load_dotenv(path='.env'):
    """Read simple KEY=VALUE lines from .env and set os.environ for missing keys.
    If DATABASE_URL is not present but POSTGRES_* vars exist, construct DATABASE_URL
    and append it to the .env file so future runs see it.
    """
    try:
        if not os.path.exists(path):
            return
        existing = {}
        with open(path, 'r', encoding='utf-8') as f:
            for ln in f:
                ln = ln.strip()
                if not ln or ln.startswith('#') or '=' not in ln:
                    continue
                k, v = ln.split('=', 1)
                k = k.strip()
                v = v.strip().strip('"').strip("'")
                existing[k] = v
                # only set if not already in environment
                os.environ.setdefault(k, v)

        # ensure DATABASE_URL exists when Postgres pieces are present
        if not os.environ.get('DATABASE_URL'):
            user = os.environ.get('POSTGRES_USER') or existing.get('POSTGRES_USER')
            pwd = os.environ.get('POSTGRES_PASSWORD') or existing.get('POSTGRES_PASSWORD')
            dbn = os.environ.get('POSTGRES_DB') or existing.get('POSTGRES_DB')
            host = os.environ.get('POSTGRES_HOST') or existing.get('POSTGRES_HOST') or 'localhost'
            port = os.environ.get('POSTGRES_PORT') or existing.get('POSTGRES_PORT') or '5432'
            if user and pwd and dbn:
                dsn = f'postgresql://{user}:{pwd}@{host}:{port}/{dbn}'
                os.environ['DATABASE_URL'] = dsn
                # append to .env for persistence
                try:
                    with open(path, 'a', encoding='utf-8') as f:
                        f.write('\n# auto-generated by main.py\n')
                        f.write('DATABASE_URL=' + dsn + '\n')
                except Exception:
                    pass
    except Exception:
        # never fail startup due to .env parsing
        pass


